export function getLocale(): Locale {
  if (typeof window === "undefined") return "ru";
  return window.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ru";
}

export function setLocale(locale: Locale): void {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(STORAGE_KEY, locale);
  document.documentElement.lang = locale;
  window.dispatchEvent(new Event(CHANGE_EVENT));
}

function subscribe(callback: () => void): () => void {
  window.addEventListener(CHANGE_EVENT, callback);
  window.addEventListener("storage", callback);
  return () => {
    window.removeEventListener(CHANGE_EVENT, callback);
    window.removeEventListener("storage", callback);
  };
}

export function useI18n() {
  const locale = useSyncExternalStore(subscribe, getLocale, (): Locale => "ru");
  const t = (text: string, englishOverride?: string): string =>
    locale === "en"
      ? englishOverride ?? english[text] ?? (/[А-Яа-яЁё]/.test(text) ? "Something went wrong. Please try again." : text)
      : russian[text] ?? text;
  return { locale, setLocale, t };
}

export function translateApiMessage(message: string): string {
  if (getLocale() !== "en") return message;
  const floodWait = message.match(/^Слишком много попыток\. Подождите (.+) секунд?\.$/);
  if (floodWait) return `Too many attempts. Please wait ${floodWait[1]} seconds.`;
  if (message.startsWith("Проверьте данные: ")) {
    return `Check the information: ${message.slice("Проверьте данные: ".length)}`;
  }
  if (english[message]) return english[message];
  return /[А-Яа-яЁё]/.test(message) ? "The request couldn't be completed. Please try again." : message;
}
